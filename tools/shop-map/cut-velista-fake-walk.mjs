/**
 * Cuts the scripted walk velista replays instead of the camera in a dev build
 * (velista plan 0126, `?fakeWalk=1`), from the El Jamón walk log fixture of
 * shop-map plan 0002.
 *
 *   node tools/shop-map/cut-velista-fake-walk.mjs
 *
 * It reads `libs/luna-shopper/shop-map/model/src/lib/__fixtures__/el-jamon/walk-log.json`
 * and writes `libs/velista/platform/src/lib/sensors/scripted-walk-data.ts`: the
 * first six minutes of the first session's path at one point per second, and
 * the moments the walker stood facing what they marked, with the heading the
 * camera faced. Never edit the output by hand: rerun this script.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const FROM =
  'libs/luna-shopper/shop-map/model/src/lib/__fixtures__/el-jamon/walk-log.json';
const TO = 'libs/velista/platform/src/lib/sensors/scripted-walk-data.ts';
const UNTIL_MS = 360_000;

const log = JSON.parse(readFileSync(FROM, 'utf8'));
const first = log.entries[0];
const path = [];
const facing = [];
for (const event of first.events) {
  if (event.type === 'path') {
    for (const [t, x, y] of event.points) {
      if (t <= UNTIL_MS) path.push([t, x, y]);
    }
  } else if (event.type === 'mark-put' && event.mark.logMs <= UNTIL_MS) {
    facing.push([event.mark.logMs, event.mark.heading]);
  }
}

const rows = (list) => list.map((row) => `  [${row.join(', ')}],`).join('\n');
const out = `// Generated by tools/shop-map/cut-velista-fake-walk.mjs from the El Jamón walk
// log fixture (shop-map plan 0002). Never edit by hand: rerun the script.

/** \`[ms, x, y]\`: one point of the path, metres in the walk's frame. */
type PathRow = readonly [number, number, number];

/** The walker's path, one point a second. */
export const SCRIPTED_WALK_PATH: readonly PathRow[] = [
${rows(path)}
];

/** \`[ms, heading]\`: when the walker stood facing what they marked, and the heading. */
export const SCRIPTED_WALK_FACING: readonly (readonly [number, number])[] = [
${rows(facing)}
];
`;
writeFileSync(TO, out);
console.log(
  `${path.length} points and ${facing.length} facings written to ${TO}`
);
